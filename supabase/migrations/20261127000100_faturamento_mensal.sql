BEGIN;

CREATE TABLE IF NOT EXISTS public."faturamento_mensal" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loja_id bigint NOT NULL REFERENCES public.lojas(id) DEFERRABLE INITIALLY DEFERRED,
  ano integer NOT NULL CHECK (ano BETWEEN 1900 AND 9999),
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  valor_centavos bigint NOT NULL CHECK (valor_centavos BETWEEN 0 AND 999999999999),
  atualizado_por bigint REFERENCES public.usuarios(id) DEFERRABLE INITIALLY DEFERRED,
  atualizado_em text NOT NULL DEFAULT to_char(timezone('UTC', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (loja_id, ano, mes)
);
CREATE INDEX IF NOT EXISTS faturamento_mensal_ano_mes_idx ON public.faturamento_mensal (ano, mes);

ALTER TABLE public."faturamento_mensal" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.faturamento_mensal FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.faturamento_mensal_id_seq FROM PUBLIC;
DO $$
DECLARE papel text;
BEGIN
  FOREACH papel IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = papel) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I', 'faturamento_mensal', papel);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.faturamento_mensal_id_seq FROM %I', papel);
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE tinha_create boolean;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'nosso_mercadinho_api') THEN
    tinha_create := has_schema_privilege('nosso_mercadinho_api', 'public', 'CREATE');
    IF NOT tinha_create THEN GRANT CREATE ON SCHEMA public TO nosso_mercadinho_api; END IF;
    ALTER TABLE public.faturamento_mensal OWNER TO nosso_mercadinho_api;
    IF NOT tinha_create THEN REVOKE CREATE ON SCHEMA public FROM nosso_mercadinho_api; END IF;
  END IF;
END $$;

COMMIT;
